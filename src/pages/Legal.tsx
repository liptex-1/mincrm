function useOperator() {
  const a = useAbout();
  const name = a.name.trim() || 'владелец сервиса (реквизиты указаны на странице «О нас»)';
  const contacts = [a.email && `почта: ${a.email}`, a.phone && `телефон: ${a.phone}`, a.address && `адрес: ${a.address}`, a.telegram && `Telegram: ${a.telegram}`].filter(Boolean).join('; ') || 'контакты указаны на странице «О нас»';
  return { name, contacts, email: a.email.trim() };
}
